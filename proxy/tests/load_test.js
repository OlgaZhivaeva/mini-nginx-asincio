import http from 'k6/http';
import { check, sleep } from 'k6';

// Настройки теста (конфигурация нагрузки)
export const options = {
  // Эмулируем нагрузку:
  stages: [
    { duration: '5s', target: 10 },   // Плавный разгон до 10 виртуальных пользователей за 5 секунд
    { duration: '15s', target: 10 },  // Держим нагрузку в 10 пользователей 15 секунд
    { duration: '5s', target: 0 },    // Плавное затухание до 0 за 5 секунд
  ],
  // Порог успешности: 99% запросов должны завершиться без ошибок со статусом 200
  thresholds: {
    http_req_failed: ['rate<0.01'],
    http_req_duration: ['p(95)<500'], // 95% запросов должны обрабатываться быстрее 500мс
  },
};

// Функция, которую циклически выполняют виртуальные пользователи
export default function () {
  // Делаем GET-запрос на наш Мини-Nginx
  const res = http.get('http://127.0.0.1:8080/test');

  // Проверяем, что сервер ответил статусом 200
  check(res, {
    'статус равен 200': (r) => r.status === 200,
    'тело ответа содержит Upstream': (r) => r.body.includes('Upstream'),
  });

  // Пауза 1 секунда между запросами одного пользователя
  sleep(1);
}
